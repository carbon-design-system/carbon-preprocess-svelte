// Generates src/syntax.css from @carbon/themes' official `syntax-*` tokens,
// for the token types carbon-preprocess-svelte's highlighter emits.
//
//   bun scripts/gen-syntax-css.ts
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { g100, white } from "@carbon/themes";
import { TOKEN_TYPES } from "carbon-preprocess-svelte/code";

const TYPES: readonly string[] = TOKEN_TYPES;
const OUT = path.join(import.meta.dirname, "../src/syntax.css");
const { version } = JSON.parse(
  readFileSync(
    path.join(
      import.meta.dirname,
      "../node_modules/@carbon/themes/package.json",
    ),
    "utf8",
  ),
);
const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const token = (t: string) => `syntax${t[0].toUpperCase()}${t.slice(1)}`;
const block = (selector: string, theme: Record<string, string>) =>
  `${selector} {\n${TYPES.map((t) => `  --cds-syntax-${kebab(t)}: ${theme[token(t)]};`).join("\n")}\n}`;
// Diffs color the line's background; everything else colors text.
const BACKGROUND = new Set(["inserted", "deleted"]);
const rule = (selector: (t: string) => string) =>
  TYPES.map(
    (t) =>
      `${selector(t)} {\n  ${BACKGROUND.has(t) ? "background-color" : "color"}: var(--cds-syntax-${kebab(t)});\n}`,
  ).join("\n\n");
const css = `/* Generated by gen-syntax-css.ts from @carbon/themes ${version} (syntax-* tokens). */

${block(':root,\n[theme="white"],\n[theme="g10"],\n.t-white,\n.t-g10', white)}

${block('[theme="g80"],\n[theme="g90"],\n[theme="g100"],\n.t-g80,\n.t-g90,\n.t-g100', g100)}

/* Build-time: spans from \`highlight()\`. */
${rule((t) => `.syntax-build .tok-${kebab(t)}`)}

/* Runtime: the CSS Custom Highlight API; no spans needed (see highlight-dom.js). */
${rule((t) => `::highlight(syntax-${kebab(t)})`)}
`;
writeFileSync(OUT, css);
console.log(`wrote src/syntax.css (${TYPES.length} token types)`);
